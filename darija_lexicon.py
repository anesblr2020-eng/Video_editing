# ==============================================================================
# 1. التطبيع (Normalization) - للمطابقة فقط، لا للعرض
# ==============================================================================
_DIACRITICS = re.compile(r"[\u0610-\u061A\u064B-\u065F\u0670\u06D6-\u06ED\u0640]")
_PUNCT = re.compile(r"[\"'«».,،;؛:!?؟()\[\]{}<>\-_/\\|*~`^%$#@&+=…“”‘’]")
_ELONG = re.compile(r"(.)\1{2,}")

_CHAR_MAP = str.maketrans({
    "أ": "ا", "إ": "ا", "آ": "ا", "ٱ": "ا",
    "ى": "ي", "ئ": "ي", "ؤ": "و", "ة": "ه",
    "ڤ": "ف", "ڨ": "ق", "گ": "ق", "ݣ": "ق", "پ": "ب", "چ": "ش",
    "ک": "ك", "ی": "ي", "ھ": "ه",
})


def norm_ar(text: str) -> str:
    """تطبيع عربي/دارجة للمطابقة: إزالة التشكيل والتطويل وتوحيد الألف والياء والتاء المربوطة وحروف الدارجة (ڤ ڨ)."""
    if not text:
        return ""
    t = _DIACRITICS.sub("", str(text))
    t = t.translate(_CHAR_MAP).lower()
    t = _PUNCT.sub(" ", t)
    t = _ELONG.sub(r"\1\1", t)
    return re.sub(r"\s+", " ", t).strip()


_PREFIXES = ("وال", "بال", "كال", "فال", "لل", "ال", "و", "ب", "ك", "ف", "ل")


def strip_prefix(tok: str) -> str:
    """إزالة أدوات التعريف والعطف الشائعة (ال، و، ب، ل...) مع الحفاظ على جذر لا يقل عن 3 أحرف."""
    for p in _PREFIXES:
        if tok.startswith(p) and len(tok) - len(p) >= 3:
            return tok[len(p):]
    return tok


def token_matches(tok: str, stem: str) -> bool:
    """هل الكلمة (المطبّعة) تطابق جذراً/كلمة دالة؟ المطابقة بالبداية للجذور الطويلة، وبالتساوي للقصيرة."""
    if not tok or not stem:
        return False
    cands = {tok, strip_prefix(tok)}
    # تصريف الأفعال بالدارجة: ن/ت/ي + جذر (تربحو -> ربحو، نمنتج -> منتج، يتهكر -> تهكر)
    for c in list(cands):
        if len(c) >= 5 and c[0] in "نتي":
            cands.add(c[1:])
    if len(stem) <= 3:
        return stem in cands
    return any(c == stem or c.startswith(stem) for c in cands)


