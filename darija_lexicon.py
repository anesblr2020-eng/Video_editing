# عبارات مركبة شائعة (أخطاء تفريغ مؤكدة فقط)
PHRASE_FIXES: List[Tuple[str, str]] = [
    (r"\bفيس\s+بوك\b", "فيسبوك"),
    (r"\bانستا\s+غرام\b", "انستغرام"),
    (r"\bتيك\s+توك\b", "تيك توك"),
    (r"\bيو\s+تيوب\b", "يوتيوب"),
    (r"\bواتس\s+اب\b", "واتساب"),
    (r"\bبالذكاء\s+الاصطناعي\b", "بالذكاء الاصطناعي"),
]


def fix_word(word: str) -> str:
    """تصحيح كلمة واحدة مع الحفاظ على علامات الترقيم الملصقة بها."""
    if not word:
        return ""
    w = word.strip()
    core = w.strip("،,.!؟?؛:\"'«»")
    if not core:
        return w
    fixed = SAFE_WORD_FIXES.get(core)
    if fixed is None:
        fixed = SAFE_WORD_FIXES.get(_DIACRITICS.sub("", core))
    if fixed is None:
        return w
    i = w.find(core)
    return w[:i] + fixed + w[i + len(core):]


def fix_sentence(text: str) -> str:
    if not text:
        return ""
    out = " ".join(fix_word(t) for t in text.split())
    for pat, rep in PHRASE_FIXES:
        out = re.sub(pat, rep, out)
    return out


