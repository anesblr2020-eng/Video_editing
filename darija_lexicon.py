def extract_spoken_numbers(text: str) -> List[Dict[str, object]]:
    """
    يستخرج فقط الأرقام التي نطقها المتحدث فعلاً (أرقام رقمية أو كلمات رقمية دارجة) مع الوحدة التالية لها إن وجدت.
    ترجع قائمة: {"value": int, "unit": str|None, "raw": str}
    لا تخمّن أرقاماً أبداً.
    """
    out: List[Dict[str, object]] = []
    if not text:
        return out
    t = str(text).translate(_AR_INDIC)
    toks = norm_ar(t).split()
    for i, tok in enumerate(toks):
        val: Optional[int] = None
        m = re.fullmatch(r"(\d+(?:[.,]\d+)?)(%?)", tok)
        if m:
            try:
                val = int(float(m.group(1).replace(",", ".")))
            except ValueError:
                val = None
            unit = "%" if m.group(2) else None
        else:
            if tok in NUMBER_WORDS and tok not in ("واحد", "وحده", "ربع"):
                val = NUMBER_WORDS[tok]
            unit = None
        if val is None:
            continue
        if unit is None and i + 1 < len(toks):
            nxt = toks[i + 1]
            for keys, label in UNIT_LABEL:
                if any(token_matches(nxt, k) for k in keys):
                    unit = label
                    break
        out.append({"value": val, "unit": unit, "raw": tok})
    return out


