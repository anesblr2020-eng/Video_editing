def is_negated(tokens: List[str], i: int) -> bool:
    """نفي الدارجة: «ما + فعل + ش» (ما يتقطعش، ماخدمش، ماعندوش) أو «ماكانش/مكانش»."""
    t = tokens[i]
    if t.endswith("ش") and len(t) >= 4:
        if t.startswith("ما") or t.startswith("م"):
            return True
        if i > 0 and tokens[i - 1] in ("ما", "مي"):
            return True
    if i > 0 and tokens[i - 1] in ("ما", "مي") and t.endswith("ش"):
        return True
    return False
